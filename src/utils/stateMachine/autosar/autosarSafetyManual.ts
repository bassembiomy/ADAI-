import type { SwcRenderContext } from './autosarSwc';
import { traceLines } from './autosarTrace';

const lines = (...parts: string[]): string => `${parts.join('\n')}\n`;

/**
 * Safety Manual of the ADIA AUTOSAR generator for one package: how the tool may be used, its
 * ISO 26262-8 clause 11 classification, its known limitations and what the integrator must do.
 */
export const renderSafetyManual = (ctx: SwcRenderContext): string => lines(
  `# Safety manual of the ADIA AUTOSAR generator - ${ctx.swc}`,
  '',
  ...traceLines(ctx.fingerprint),
  '',
  'This manual describes the software tool that produced this package (the ADIA AUTOSAR generator) in the',
  'terms of ISO 26262-8 clause 11 (confidence in the use of software tools). The tool and this package are',
  'not certified and not qualified; this manual and `Verification_Report.md` provide the inputs an integrator needs',
  'for the tool qualification and the safety case of the item.',
  '',
  '## 1. Intended use',
  '',
  'The tool turns a validated ADIA state-machine model into an AUTOSAR Classic Platform (R4.x) application',
  'software component: C sources (runnables, state-machine core), the ARXML description, host-only RTE stubs, a',
  'host unit test and documents. It is a code generator; it does not assign an ASIL (the ASIL comes from the',
  'hazard analysis and risk assessment of the item) and it does not generate the integration with the target',
  'platform.',
  '',
  '## 2. Tool usage constraints',
  '',
  '- Use only models that pass ADIA model validation; the generator refuses a model with errors and reports them.',
  '- The tick period must be a positive integer number of milliseconds; the TimingEvent period equals it.',
  '- Variables of 64-bit integer type are evaluated in double precision by the core (53-bit mantissa); the',
  '  generator warns about them. Do not rely on exact arithmetic beyond 2^53 for such variables.',
  '- Variables that no guard, action or X-Bridges mapping reads or writes get no port; the generator warns.',
  '- `stubs/` and `test/` are host-only stand-ins. Replace the stubs by the stack\'s own `Std_Types.h`,',
  '  `Platform_Types.h`, `Compiler.h`, `Compiler_Cfg.h`, `<SWC>_MemMap.h` and the generated RTE.',
  '- Do not define `ADIA_TESTING` in a production build: it enables the test hooks only.',
  '- Do not edit the generated files by hand; regenerate. `SHA256SUMS` and the fingerprint detect changes.',
  '- Run `npm run verify:autosar` (or the Makefile) on the exact package that is integrated and keep the evidence.',
  '',
  '## 3. Tool classification (ISO 26262-8 clause 11)',
  '',
  'The classification below is the generator\'s proposal. The integrator confirms it for the concrete use case.',
  '',
  '| Criterion | Assessment | Rationale |',
  '|---|---|---|',
  '| Tool Impact (TI) | TI2 | The generator output is part of the item\'s software; an error in the tool can introduce an error into it. |',
  '| Tool error Detection (TD) | TD2 when the verification gates are run on the delivered package, otherwise TD3 | Compilation with two compilers, static analysis, sanitizers, a host unit test with coverage, a differential comparison against ADIA\'s model interpreter and a reproducible-build check detect many tool errors; they do not detect all of them. |',
  '| Tool Confidence Level (TCL) | TCL2 with the gates run (TI2 and TD2), TCL3 without them (TI2 and TD3) | Derived from the TI and TD levels with the table of ISO 26262-8 clause 11. |',
  '',
  'Depending on the ASIL of the item and the resulting TCL, clause 11 asks for one or more qualification',
  'methods: increased confidence from use, evaluation of the tool development process, or validation of the',
  'software tool. ADIA supplies the validation evidence of this package; the qualification itself is an',
  'integrator activity.',
  '',
  '## 4. Verification evidence the tool provides',
  '',
  '| Gate | Detects |',
  '|---|---|',
  '| generation | Generator errors and package drift from the generator output. |',
  '| misra-subset | Violations of the textually decidable MISRA C:2012 rules. |',
  '| arxml-structure | Malformed ARXML and unresolved references (not an XSD validation). |',
  '| host-build | Compile errors and warnings with gcc `-std=c99 -pedantic-errors -Wall -Wextra -Werror`. |',
  '| unit-test | Functional errors visible to the generated host test. |',
  '| coverage | Untested statements and branches of the component (gcov: 100 % lines, at least 90 % branches taken). |',
  '| static-analysis | Defects found by `gcc -fanalyzer`. |',
  '| sanitizers | Memory and undefined-behaviour errors (AddressSanitizer, UndefinedBehaviorSanitizer). |',
  '| second-compiler | Compiler-dependent behaviour (clang build and test run). |',
  '| differential | Differences between the generated C and ADIA\'s semantic interpreter on seeded random input sequences. |',
  '| reproducible-build | Non-reproducible object code (two builds in different directories must be byte-identical). |',
  '',
  'A gate that did not run (tool missing, not selected) is reported as NOT RUN and never as PASS.',
  '',
  '## 5. Known limitations',
  '',
  '- The MISRA checker is a textual subset (comment- and literal-stripped source); it is not a qualified MISRA tool.',
  '- No AUTOSAR XSD ships with ADIA; the ARXML is checked structurally only.',
  '- Evidence is produced on a host (x86-64) with gcc and clang; the target compiler, the target hardware and',
  '  the real RTE are not part of it.',
  '- The differential gate compares the generated C with the ADIA interpreter. Both implement the same model',
  '  semantics, so a misunderstanding of the modelling language shared by both is not detected.',
  '- Floating-point values are compared bit-exact or within 1e-12 relative error; non-finite floating-point',
  '  inputs are covered by the unit tests, not by the differential vectors.',
  '- Only runnable-level behaviour is verified; timing, scheduling, memory protection and the OS are outside it.',
  '',
  '## 6. Activities required from the integrator',
  '',
  '1. Derive the ASIL and the safety requirements of the component from the HARA; map them to the model.',
  '2. Run a qualified MISRA C:2012 checker on the production configuration and justify its deviations.',
  '3. Validate the ARXML against the AUTOSAR XSD of the stack release and import it in the authoring tool.',
  '4. Build with the target compiler and options, and run the tests on the target or a HIL setup.',
  '5. Integrate with the real RTE and BSW (Dem, scheduler) and perform the integration tests.',
  '6. Qualify the tool for the use case according to ISO 26262-8 clause 11, using this manual and the report.',
  '7. Keep the verification evidence and the `SHA256SUMS` of the delivered package under configuration management.',
);
