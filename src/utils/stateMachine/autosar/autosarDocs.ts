import { CHECKED_MISRA_RULES, type MisraFinding } from './autosarMisraChecker';
import type { SwcRenderContext } from './autosarSwc';
import { traceLines } from './autosarTrace';

export interface DocsContext extends SwcRenderContext {
  findings: readonly MisraFinding[];
  checkedFiles: readonly string[];
  safetyMode: boolean;
  hasXBridges: boolean;
  /** Generator warnings, e.g. excluded variables or 64-bit precision. */
  warnings: readonly string[];
}

const lines = (...parts: Array<string | null | undefined>): string =>
  `${parts.filter((part): part is string => typeof part === 'string').join('\n')}\n`;

export const renderMisraCompliance = (ctx: DocsContext): string => {
  const result = ctx.findings.length === 0
    ? `No finding in ${ctx.checkedFiles.length} checked source files.`
    : `${ctx.findings.length} finding(s):`;
  return lines(
    `# MISRA C:2012 compliance - ${ctx.swc}`,
    '',
    ...traceLines(ctx.fingerprint),
    '',
    'This package was produced by the ADIA AUTOSAR Classic generator. The state-machine core is the same',
    'verified core that Generate C/H emits; the software component (`swc/`) wraps it with RTE access.',
    '',
    '## Important',
    '',
    'The generator runs a textual MISRA C:2012 subset checker. It decides only rules that can be decided on',
    'comment- and literal-stripped source text. **A qualified MISRA checker (for example Polyspace, Helix QAC,',
    'PC-lint Plus or Coverity) must be run by the integrator on the production configuration; this document',
    'is not a compliance claim for the full guideline set.**',
    '',
    '## Rules checked by the generator',
    '',
    '| Rule | Description |',
    '|---|---|',
    ...CHECKED_MISRA_RULES.map((item) => `| ${item.rule} | ${item.summary} |`),
    '',
    'Rule 17.7 (return values shall be used) is met by construction: every call in `swc/' + ctx.swc + '.c` either',
    'stores the result (`SM_Step`, `Rte_Read_*`) or casts it to `(void)` (`Rte_Write_*`, `Rte_Call_*`, `SM_Init`).',
    'It is reviewed, not machine-checked, by this package.',
    '',
    '## Result of the checker for this package',
    '',
    `Checked files: ${ctx.checkedFiles.join(', ')}`,
    '',
    result,
    ...ctx.findings.map((item) => `- ${item.rule} ${item.file}:${item.line} ${item.message}`),
    '',
    '## Documented deviations',
    '',
    'Every deviation has an id (DEV-n), the guideline it deviates from and a rationale.',
    '',
    '| Id | Guideline | Where | Rationale |',
    '|---|---|---|---|',
    '| DEV-1 | Dir 4.9 / Rule 20.7 (macros) | `stubs/Compiler.h` | Compiler abstraction macros (FUNC, P2VAR, ...) are mandated by AUTOSAR; they replace types and storage classes. |',
    '| DEV-2 | Rule 21.2 / Dir 4.6 | `core/sm_core.c` | The core uses `<math.h>`, `<string.h>` (memset) and the plain `double` type for model variables of floating-point type. Floating-point semantics are specified by the model. |',
    '| DEV-3 | Rule 8.9 (memory sections) | `core/*.c` | Constant tables are placed in the code section (`' + ctx.swc + '_START_SEC_CODE`); move them to a CONST section in the integrator MemMap if the target requires it. |',
    '| DEV-4 | Rule 20.9 / Rule 8.4 (test hook) | `swc/' + ctx.swc + '.c` | `' + ctx.swc + '_Test_GetInstance` and the core `SM_Test_*` functions exist only when `ADIA_TESTING` is defined (host unit test). A production build does not define it and contains no `_Test_` symbol. |',
    ctx.ports.required.some((port) => port.platformType.startsWith('float'))
      ? '| DEV-5 | Rule 21.11 / Dir 4.11 | `swc/' + ctx.swc + '.c` | `isfinite()` from `<math.h>` rejects NaN/Inf read from the bus; it is the portable C99 test, no value of the input is used before it passes. |'
      : null,
    ctx.hasXBridges ? '| DEV-6 | Dir 4.12 / Rule 21.x | `core/sm_xbridges.c` | The X-Bridges numeric blocks use `<math.h>` functions (isnan, floor, fabs, ...); no dynamic memory is used. |' : null,
    '',
    '`stubs/` and `test/` are host-only and not part of the production MISRA scope.',
    '',
    '## Other rules respected by construction',
    '',
    '- No `goto`, no dynamic memory, no standard I/O, no variadic functions in `swc/` and `core/`.',
    '- Every `if`, `else`, `for`, `while` and `do` body is a compound statement.',
    '- Unsigned literals carry an upper-case `U` suffix; type conversions between AUTOSAR types and core types are explicit casts.',
    '',
  );
};

export const renderIntegrationGuide = (ctx: DocsContext): string => {
  const { swc, swcUpper, ports, tickMs } = ctx;
  const row = (port: { portName: string; interfaceName: string; dataElementName: string; platformType: string; initValue: string }, direction: string, api: string): string =>
    `| ${port.portName} | ${direction} | ${port.interfaceName} | ${port.dataElementName} | ${port.platformType} | ${port.initValue} | ${api}_${port.portName}_${port.dataElementName} |`;
  const excluded = ctx.warnings.filter((item) => item.includes('[AUTOSAR_UNUSED_VARIABLE]') || item.includes('[AUTOSAR_64BIT_PRECISION]'));
  return lines(
    `# Integration guide - ${swc}`,
    '',
    ...traceLines(ctx.fingerprint),
    '',
    `AUTOSAR Classic Platform (R4.x) application software component \`${swc}\`, generated by ADIA from a state machine.`,
    '',
    '## Package layout',
    '',
    '| Folder | Content |',
    '|---|---|',
    '| `swc/` | Component sources: runnables and version macros. |',
    '| `core/` | Verified state-machine core (no MCAL access). |',
    '| `arxml/` | Software-component description to import into the authoring tool. |',
    '| `stubs/` | Host-only stand-ins for the AUTOSAR stack (replace on integration). |',
    '| `test/`, `Makefile` | Host unit test (`make test`). |',
    '| `doc/` | This guide and the MISRA compliance document. |',
    '',
    '## Ports',
    '',
    '| Port | Direction | Interface | Data element | Type | Init value | RTE API |',
    '|---|---|---|---|---|---|---|',
    ...ports.required.map((port) => row(port, 'required', 'Rte_Read')),
    ...ports.provided.map((port) => row(port, 'provided', 'Rte_Write')),
    '| PP_SmStatus | provided | SRI_SmStatus | ActiveState | uint16 | 0 | Rte_Write_PP_SmStatus_ActiveState |',
    '| PP_SmStatus | provided | SRI_SmStatus | ErrorStatus | uint8 | 0 | Rte_Write_PP_SmStatus_ErrorStatus |',
    '| RP_SmFaultEvent | required | CSI_DemEvent | SetEventStatus(IN uint8 EventStatus) | uint8 | - | Rte_Call_RP_SmFaultEvent_SetEventStatus |',
    '',
    'A variable assigned by any action of the model (state entry/during/exit, transition actions, X-Bridges outputs)',
    'is a provided port; every other variable is a required port. Required ports are read with `Rte_Read_*`;',
    'the value is accepted only when the status is `RTE_E_OK` or `RTE_E_LOST_DATA` (an overlaid flag: the data is',
    'valid). On any other status, or when a float value is NaN/Inf, the last valid value is kept and the read counts',
    'as a failure.',
    '',
    ...(excluded.length > 0 ? ['Generator notes for this model:', '', ...excluded.map((item) => `- ${item}`), ''] : []),
    '## RTE error limit',
    '',
    `Per required port the generated code counts consecutive failed reads (saturating, never wraps). When any port`,
    `reaches \`${swcUpper}_RTE_ERROR_LIMIT\` (default \`10U\`, defined in \`swc/${swc}.h\` with \`#ifndef\`, override with`,
    `\`-D${swcUpper}_RTE_ERROR_LIMIT=<n>U\`) \`MainFunction\` reports \`DEM_EVENT_STATUS_FAILED\`. One good read of that port`,
    'clears its counter and the event is reported as passed again (if the core reports no error).',
    '',
    '## Runnables and events',
    '',
    '| Runnable | Symbol | Event | Period |',
    '|---|---|---|---|',
    `| ${swc}_Init | \`${swc}_Init\` | InitEvent | - |`,
    `| ${swc}_MainFunction | \`${swc}_MainFunction\` | TimingEvent | ${tickMs} ms (${swcUpper}_PERIOD_MS = ${tickMs}) |`,
    '',
    `Period: ${tickMs} ms. The runnables are not re-entrant (\`CAN-BE-INVOKED-CONCURRENTLY\` = false) and the component`,
    'instance is static (\`SUPPORTS-MULTIPLE-INSTANTIATION\` = false): map both runnables to the same OS task.',
    '',
    `The period must equal the model tick (${tickMs} ms); the core rejects steps outside the tick tolerance`,
    '(error status reported on `PP_SmStatus.ErrorStatus` and to the Dem).',
    '',
    '## Memory sections',
    '',
    `Every source places its content between \`${swc}_START_SEC_<name>\` / \`${swc}_STOP_SEC_<name>\` and includes \`${swc}_MemMap.h\`.`,
    'Sections used: `CODE` (all code and constant tables) and `VAR_CLEARED_UNSPECIFIED` (the state-machine instance).',
    `Add both to the integrator's MemMap and map \`${swc}_CODE\` in Compiler_Cfg.h.`,
    '',
    '## Dem event',
    '',
    'Each cycle `RP_SmFaultEvent.SetEventStatus` receives `DEM_EVENT_STATUS_FAILED` (0x01) while the core reports an',
    'error or a required port reached the RTE error limit, and `DEM_EVENT_STATUS_PASSED` (0x00) otherwise. Map the',
    'port to a configured Dem event in the system description.',
    '',
    ctx.safetyMode
      ? 'Safety mode: on a fault the core enters the safe state and calls `SM_Platform_ApplySafeOutputs()` (in `swc/' + swc + '.c`). The safe values reach the provided ports because the runnable writes every provided port from the instance data after each step.'
      : null,
    '',
    '## Replacing the stubs',
    '',
    '1. Delete `stubs/` from the production build (keep it for host tests).',
    `2. Provide \`Std_Types.h\`, \`Platform_Types.h\`, \`Compiler.h\`, \`Compiler_Cfg.h\`, \`${swc}_MemMap.h\` and \`Rte_${swc}.h\` from your AUTOSAR stack / RTE generator.`,
    `3. The RTE generator creates \`Rte_${swc}.h\` from the imported ARXML; it must provide the \`Rte_Read_*\`, \`Rte_Write_*\` and \`Rte_Call_*\` functions listed above.`,
    '4. Add `swc/*.c` and `core/*.c` to the build; keep `swc/` and `core/` on the include path.',
    '',
    '## ARXML import',
    '',
    `Import \`arxml/${swc}.arxml\` into the authoring tool (schema namespace \`http://autosar.org/schema/r4.0\`).`,
    'It references the implementation data types of the standard `/AUTOSAR_Platform/ImplementationDataTypes` package,',
    'which must exist in the project. The file is checked structurally by ADIA (well-formed, all references resolve);',
    'it is not validated against the AUTOSAR XSD here - validate it in your tool.',
    '',
    '## Host test',
    '',
    '`make test` compiles with `-std=c99 -pedantic-errors -Wall -Wextra -Werror -DADIA_TESTING` and runs `test/test_' + swc + '.c`.',
    'The test drives every path of `swc/' + swc + '.c` (read accept/reject per port, non-finite floats, RTE error limit, forced core fault).',
    '',
    '## Traceability',
    '',
    'Every deliverable carries the generator version and the model fingerprint (a 64-bit FNV-1a hash of the',
    'canonical semantic model). Equal fingerprints mean the same model.',
    '',
    ...traceLines(ctx.fingerprint),
    '',
    '## ISO 26262',
    '',
    'The generator does not assign an ASIL. The ASIL, its decomposition and the required verification evidence come from the',
    'item HARA and safety concept. The code carries no qualification claim: the code generator and tool chain must be qualified',
    'according to ISO 26262-8 clause 11 in the project context, and a qualified MISRA checker run is required (see `MISRA_Compliance.md`).',
    '',
  );
};
