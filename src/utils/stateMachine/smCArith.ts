import { arithmeticModeFor } from './smArithmetic';

/*
 * Arithmetic helper section of the generated sm_core.h: the arithmetic helpers behind the typed expressions of smCExpressions.ts.
 * See smArithmetic.ts for the semantics; the simulation implements the very same rules.
 *
 * Errors: a helper that detects an arithmetic error latches SM_ERR_ARITHMETIC on the instance
 * (only when error_status is still SM_ERR_NONE, so the first error wins) and raises
 * instance->arith_pending. The enclosing guard (SM_GuardOk) or assignment (SM_Store*) consumes
 * the flag: the guard is false, the assignment is skipped. The tick then finishes and
 * SM_Step / SM_Init / SM_Reset enter the fault configuration.
 */
export const renderArithSection = (cStandard: string | undefined): string => {
  const int64 = arithmeticModeFor(cStandard) === 'int64';
  const common = [
    '#include <float.h>',
    '#include <math.h>',
    '',
    '#if defined(__STDC_VERSION__) && (__STDC_VERSION__ >= 199901L)',
    '#define SM_ARITH_INLINE static inline',
    '#elif defined(__GNUC__)',
    '#define SM_ARITH_INLINE static __inline__',
    '#else',
    '#define SM_ARITH_INLINE static',
    '#endif',
    '',
    '/* Latches the arithmetic error; the first error of the tick wins. */',
    'SM_ARITH_INLINE void SM_ArithLatch(ADIA_Instance_t *instance)',
    '{',
    '    if (instance->error_status == SM_ERR_NONE) {',
    '        instance->error_status = SM_ERR_ARITHMETIC;',
    '    }',
    '}',
    '',
    'SM_ARITH_INLINE void SM_ArithFault(ADIA_Instance_t *instance)',
    '{',
    '    SM_ArithLatch(instance);',
    '    instance->arith_pending = true;',
    '}',
    '',
    '/* Returns true when no arithmetic error occurred since the last consumption. */',
    'SM_ARITH_INLINE bool SM_ArithTake(ADIA_Instance_t *instance)',
    '{',
    '    const bool clean = !instance->arith_pending;',
    '    instance->arith_pending = false;',
    '    return clean;',
    '}',
    '',
    'SM_ARITH_INLINE bool SM_GuardOk(ADIA_Instance_t *instance, bool value)',
    '{',
    '    const bool clean = SM_ArithTake(instance);',
    '    return clean && value;',
    '}',
    '',
    'SM_ARITH_INLINE double SM_ChkD(ADIA_Instance_t *instance, double value)',
    '{',
    '    if ((value - value) != 0.0) {',
    '        SM_ArithFault(instance);',
    '        return 0.0;',
    '    }',
    '    return value;',
    '}',
    '',
    'SM_ARITH_INLINE double SM_DivD(ADIA_Instance_t *instance, double a, double b)',
    '{',
    '    if (b == 0.0) {',
    '        SM_ArithFault(instance);',
    '        return 0.0;',
    '    }',
    '    return SM_ChkD(instance, a / b);',
    '}',
    '',
    'SM_ARITH_INLINE double SM_RemD(ADIA_Instance_t *instance, double a, double b)',
    '{',
    '    if (b == 0.0) {',
    '        SM_ArithFault(instance);',
    '        return 0.0;',
    '    }',
    '    return SM_ChkD(instance, fmod(a, b));',
    '}',
    '',
    'SM_ARITH_INLINE bool SM_StoreBool(ADIA_Instance_t *instance, bool value, bool *out)',
    '{',
    '    if (!SM_ArithTake(instance)) {',
    '        return false;',
    '    }',
    '    *out = value;',
    '    return true;',
    '}',
    '',
    'SM_ARITH_INLINE bool SM_StoreDouble(ADIA_Instance_t *instance, double value, double *out)',
    '{',
    '    if (!SM_ArithTake(instance)) {',
    '        return false;',
    '    }',
    '    if ((value - value) != 0.0) {',
    '        SM_ArithLatch(instance);',
    '        return false;',
    '    }',
    '    *out = value;',
    '    return true;',
    '}',
    '',
    '/* float/single saturate to +-FLT_MAX (or fail under overflow policy error). */',
    'SM_ARITH_INLINE bool SM_StoreFloat(ADIA_Instance_t *instance, double value, bool error_on_overflow, float *out)',
    '{',
    '    if (!SM_ArithTake(instance)) {',
    '        return false;',
    '    }',
    '    if ((value - value) != 0.0) {',
    '        SM_ArithLatch(instance);',
    '        return false;',
    '    }',
    '    if ((value > (double)FLT_MAX) || (value < -(double)FLT_MAX)) {',
    '        if (error_on_overflow) {',
    '            SM_ArithLatch(instance);',
    '            return false;',
    '        }',
    '        value = (value < 0.0) ? -(double)FLT_MAX : (double)FLT_MAX;',
    '    }',
    '    *out = (float)value;',
    '    return true;',
    '}',
    '',
  ];
  const wide = [
    '/* Integer expressions: signed 64-bit intermediates that saturate and never wrap. */',
    'SM_ARITH_INLINE int64_t SM_AddI64(int64_t a, int64_t b)',
    '{',
    '    if ((b > 0) && (a > (INT64_MAX - b))) {',
    '        return INT64_MAX;',
    '    }',
    '    if ((b < 0) && (a < (INT64_MIN - b))) {',
    '        return INT64_MIN;',
    '    }',
    '    return a + b;',
    '}',
    '',
    'SM_ARITH_INLINE int64_t SM_SubI64(int64_t a, int64_t b)',
    '{',
    '    if ((b < 0) && (a > (INT64_MAX + b))) {',
    '        return INT64_MAX;',
    '    }',
    '    if ((b > 0) && (a < (INT64_MIN + b))) {',
    '        return INT64_MIN;',
    '    }',
    '    return a - b;',
    '}',
    '',
    'SM_ARITH_INLINE int64_t SM_MulI64(int64_t a, int64_t b)',
    '{',
    '    if ((a == 0) || (b == 0)) {',
    '        return 0;',
    '    }',
    '    if (a > 0) {',
    '        if (b > 0) {',
    '            if (a > (INT64_MAX / b)) {',
    '                return INT64_MAX;',
    '            }',
    '        } else if (b < (INT64_MIN / a)) {',
    '            return INT64_MIN;',
    '        }',
    '    } else if (b > 0) {',
    '        if (a < (INT64_MIN / b)) {',
    '            return INT64_MIN;',
    '        }',
    '    } else if (a < (INT64_MAX / b)) {',
    '        return INT64_MAX;',
    '    }',
    '    return a * b;',
    '}',
    '',
    'SM_ARITH_INLINE int64_t SM_NegI64(int64_t a)',
    '{',
    '    return SM_SubI64(0, a);',
    '}',
    '',
    'SM_ARITH_INLINE int64_t SM_AbsI64(int64_t a)',
    '{',
    '    return (a < 0) ? SM_NegI64(a) : a;',
    '}',
    '',
    'SM_ARITH_INLINE int64_t SM_DivI64(ADIA_Instance_t *instance, int64_t a, int64_t b)',
    '{',
    '    if (b == 0) {',
    '        SM_ArithFault(instance);',
    '        return 0;',
    '    }',
    '    if ((a == INT64_MIN) && (b == -1)) {',
    '        return INT64_MAX;',
    '    }',
    '    return a / b;',
    '}',
    '',
    'SM_ARITH_INLINE int64_t SM_RemI64(ADIA_Instance_t *instance, int64_t a, int64_t b)',
    '{',
    '    if (b == 0) {',
    '        SM_ArithFault(instance);',
    '        return 0;',
    '    }',
    '    if (b == -1) {',
    '        return 0;',
    '    }',
    '    return a % b;',
    '}',
    '',
    '/* An unsigned 64-bit variable read as an int64 operand saturates at INT64_MAX. */',
    'SM_ARITH_INLINE int64_t SM_U64ToI64(uint64_t value)',
    '{',
    '    return (value > (uint64_t)INT64_MAX) ? INT64_MAX : (int64_t)value;',
    '}',
    '',
    '/* Converts to the target range: saturates, or fails under overflow policy error. */',
    'SM_ARITH_INLINE bool SM_StoreI64(ADIA_Instance_t *instance, int64_t value, int64_t lo, int64_t hi, bool error_on_overflow, int64_t *out)',
    '{',
    '    if (!SM_ArithTake(instance)) {',
    '        return false;',
    '    }',
    '    if ((value < lo) || (value > hi)) {',
    '        if (error_on_overflow) {',
    '            SM_ArithLatch(instance);',
    '            return false;',
    '        }',
    '        value = (value < lo) ? lo : hi;',
    '    }',
    '    *out = value;',
    '    return true;',
    '}',
    '',
    '/* Floating to integer: truncates toward zero, then as SM_StoreI64. */',
    'SM_ARITH_INLINE bool SM_StoreDoubleToI64(ADIA_Instance_t *instance, double value, int64_t lo, int64_t hi, bool error_on_overflow, int64_t *out)',
    '{',
    '    int64_t wide;',
    '    bool beyond = false;',
    '    if (!SM_ArithTake(instance)) {',
    '        return false;',
    '    }',
    '    if ((value - value) != 0.0) {',
    '        SM_ArithLatch(instance);',
    '        return false;',
    '    }',
    '    if (value >= 9223372036854775808.0) {',
    '        wide = INT64_MAX;',
    '        beyond = true;',
    '    } else if (value < -9223372036854775808.0) {',
    '        wide = INT64_MIN;',
    '        beyond = true;',
    '    } else {',
    '        wide = (int64_t)value;',
    '    }',
    '    if (beyond || (wide < lo) || (wide > hi)) {',
    '        if (error_on_overflow) {',
    '            SM_ArithLatch(instance);',
    '            return false;',
    '        }',
    '        wide = (wide < lo) ? lo : ((wide > hi) ? hi : wide);',
    '    }',
    '    *out = wide;',
    '    return true;',
    '}',
    '',
  ];
  const narrow = [
    '/* C90 has no 64-bit type: integer expressions are evaluated in double (exact up to 2^53). */',
    'SM_ARITH_INLINE double SM_TruncD(double value)',
    '{',
    '    return (value < 0.0) ? ceil(value) : floor(value);',
    '}',
    '',
    'SM_ARITH_INLINE double SM_DivInt(ADIA_Instance_t *instance, double a, double b)',
    '{',
    '    if (b == 0.0) {',
    '        SM_ArithFault(instance);',
    '        return 0.0;',
    '    }',
    '    return SM_ChkD(instance, SM_TruncD(a / b));',
    '}',
    '',
    'SM_ARITH_INLINE bool SM_StoreIntD(ADIA_Instance_t *instance, double value, double lo, double hi, bool error_on_overflow, double *out)',
    '{',
    '    if (!SM_ArithTake(instance)) {',
    '        return false;',
    '    }',
    '    if ((value - value) != 0.0) {',
    '        SM_ArithLatch(instance);',
    '        return false;',
    '    }',
    '    value = SM_TruncD(value);',
    '    if ((value < lo) || (value > hi)) {',
    '        if (error_on_overflow) {',
    '            SM_ArithLatch(instance);',
    '            return false;',
    '        }',
    '        value = (value < lo) ? lo : hi;',
    '    }',
    '    *out = value + 0.0;',
    '    return true;',
    '}',
    '',
  ];
  return [...common, ...(int64 ? wide : narrow)].join('\n');
};
