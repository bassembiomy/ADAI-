/**
 * Regenerates src/engine/vlab/vlabRequiredPorts.ts from the live tree (WP-07).
 * Run: npx tsx scripts/vlab_review/genRequiredPorts.ts
 * connections.test.ts fails whenever the committed tables differ from a fresh derivation (ratchet).
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { deriveRequiredTables } from '../../src/engine/vlab/review/requiredPorts';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const t = deriveRequiredTables();
const lit = (name: string, tbl: Record<string, string[]>) =>
  `export const ${name}: Readonly<Record<string, readonly string[]>> = {\n` +
  Object.entries(tbl).map(([k, v]) => `  ${/^[A-Za-z_]\w*$/.test(k) ? k : `'${k}'`}: [${v.map(p => `'${p}'`).join(', ')}],`).join('\n') +
  '\n};\n';
const out = `/**
 * GENERATED by scripts/vlab_review/genRequiredPorts.ts from src/engine/vlab/review/requiredPorts.ts (WP-07). Do not hand-edit.
 * Raw derivation, before the documented semantic exemptions applied in vlabTopologyValidation.ts.
 * Blocks absent from a table have no required ports of that kind.
 *  - signal: input ports the equation consumes while unwired (no inputOrParam parameter fallback)
 *  - conserving: ports whose being open makes the block structurally singular (Jacobian rank analysis; frame ports excluded)
 */
${lit('DERIVED_REQUIRED_SIGNAL_INPUTS', t.signal)}
${lit('DERIVED_REQUIRED_CONSERVING_PORTS', t.conserving)}
/** Blocks already singular with every conserving port tied to a reference: not judged per port. */
export const ILL_POSED_CONSERVING_BLOCKS: readonly string[] = [${t.illPosed.map(b => `'${b}'`).join(', ')}];
`;
fs.writeFileSync(path.join(ROOT, 'src/engine/vlab/vlabRequiredPorts.ts'), out);
console.log(`signal blocks ${Object.keys(t.signal).length}, conserving blocks ${Object.keys(t.conserving).length}, ill-posed ${t.illPosed.length}`);
