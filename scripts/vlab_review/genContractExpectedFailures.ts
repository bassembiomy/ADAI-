/**
 * Regenerates src/engine/vlab/review/contractExpectedFailures.ts from the live tree (WP-03 ratchet baseline).
 * Run: npx tsx scripts/vlab_review/genContractExpectedFailures.ts
 *
 * Only run this to ADD baseline entries for a newly added block. When a later WP fixes a block, its
 * it.fails starts failing: delete that entry by hand (or regenerate) - never keep a stale entry.
 */
import * as fs from 'node:fs';
import * as path from 'node:path';
import { fileURLToPath } from 'node:url';
import { CHECK_IDS, buildContexts, evaluateBlock, wpFor, type ExpectedFailures } from '../../src/engine/vlab/review/contractChecks';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const map: ExpectedFailures = {};
const unmapped: string[] = [];
for (const ctx of buildContexts()) {
  const res = evaluateBlock(ctx);
  for (const check of CHECK_IDS) {
    if (!res[check].length) continue;
    const wp = wpFor(ctx, check);
    if (!wp) { unmapped.push(`${ctx.block.id}:${check}: ${res[check].join('; ')}`); continue; }
    (map[ctx.block.id] ||= {})[check] = wp;
  }
}
if (unmapped.length) {
  console.error('Failures with no owning WP (fix the contract or the block, they cannot be expected):\n' + unmapped.join('\n'));
  process.exit(1);
}
const ids = Object.keys(map).sort();
const body = ids.map(id => {
  const entries = CHECK_IDS.filter(c => map[id][c]).map(c => `'${c}': '${map[id][c]}'`).join(', ');
  return `  ${/^[A-Za-z_]\w*$/.test(id) ? id : `'${id}'`}: { ${entries} },`;
}).join('\n');
const out = `/**
 * GENERATED by scripts/vlab_review/genContractExpectedFailures.ts (WP-03). blockId -> check id -> owning WP.
 * Each entry runs as it.fails in contract.test.ts. When the owning WP fixes the block the it.fails turns red:
 * delete the entry. Never add an entry by hand to hide a regression.
 */
import type { ExpectedFailures } from './contractChecks';

export const CONTRACT_EXPECTED_FAILURES: ExpectedFailures = {
${body}
};
`;
fs.writeFileSync(path.join(ROOT, 'src/engine/vlab/review/contractExpectedFailures.ts'), out);
console.log(`wrote ${ids.length} blocks, ${ids.reduce((n, i) => n + Object.keys(map[i]).length, 0)} expected failures`);
