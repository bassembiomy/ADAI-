const { chromium } = require('@playwright/test');
const fs = require('node:fs');
const { pathToFileURL } = require('node:url');

(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [], checks = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('dialog', d => d.accept());
  const assert = (value, message) => { if (!value) throw new Error(message); };
  try {
    await page.goto('http://localhost:3000', { waitUntil: 'domcontentloaded', timeout: 120000 });
    const welcome = page.locator('[data-testid="welcome-overlay"]');
    if (await welcome.count()) await welcome.click({ position: { x: 10, y: 10 }, force: true });
    await page.locator('input[type=file][accept=".adia,.json"]').setInputFiles('docs/help/audit/hmi-browser-fixture.json');
    await page.getByRole('button', { name: 'Continue', exact: true }).click();
    if (await welcome.count()) await welcome.click({ position: { x: 10, y: 10 }, force: true });
    await page.getByTitle('Open HMI Dashboard Panel').click();
    const workspace = page.locator('.hmi-workspace');
    await workspace.waitFor();
    assert(await workspace.locator('.hmi-palette button').count() === 42, 'Incomplete palette');
    assert(await workspace.evaluate(el => getComputedStyle(el).position) === 'relative', 'HMI escaped managed window');
    checks.push('42 categorized components; legacy fixture import; managed window geometry');
    await workspace.getByRole('button', { name: 'Run controls', exact: true }).click();
    const header = workspace.locator('header');
    await workspace.getByRole('button', { name: 'Request', exact: true }).press('Enter');
    assert((await workspace.innerText()).includes('Inactive · B'), 'Input advanced chart before tick');
    await header.getByRole('button', { name: 'Step', exact: true }).click();
    await workspace.getByText('● Active · B', { exact: true }).waitFor();
    assert(await workspace.locator('polyline').count() === 1, 'Committed trace missing');
    await header.getByRole('button', { name: 'Step', exact: true }).click();
    assert(await workspace.locator('[data-widget-type="lamp"] output').getAttribute('data-active') === 'false', 'Momentary release not consumed');
    checks.push('Keyboard quick press preserved for one tick; state transition; release and committed scope');
    const entry = workspace.getByRole('spinbutton', { name: 'Set total', exact: true });
    await entry.fill('25'); await entry.press('Enter');
    assert((await workspace.locator('[data-widget-type="lcd"]').innerText()).includes('0.00'), 'Staged value shown as committed');
    await workspace.getByText('Staged for next tick', { exact: true }).waitFor();
    await header.getByRole('button', { name: 'Step', exact: true }).click();
    assert((await workspace.locator('[data-widget-type="lcd"]').innerText()).includes('25.00'), 'Typed numeric staging not consumed');
    await workspace.getByRole('button', { name: 'Request', exact: true }).press('Enter');
    await header.getByRole('button', { name: 'Reset', exact: true }).click();
    await header.getByRole('button', { name: 'Step', exact: true }).click();
    assert((await workspace.innerText()).includes('Inactive · B'), 'Reset leaked queued press');
    checks.push('Paused numeric draft/commit; Reset clears queued input');
    await header.getByRole('button', { name: 'Start', exact: true }).click();
    await page.waitForFunction(() => Number(document.querySelector('.hmi-workspace header span').textContent.match(/([\d.]+) s/)[1]) >= .02);
    await header.getByRole('button', { name: 'Start', exact: true }).click();
    await page.waitForFunction(() => Number(document.querySelector('.hmi-workspace header span').textContent.match(/([\d.]+) s/)[1]) >= .02);
    await header.getByRole('button', { name: 'Pause', exact: true }).click();
    await header.getByRole('button', { name: 'Reset', exact: true }).click();
    checks.push('Start while running renews the simulation loop; Pause and Reset lifecycle');
    for (const theme of ['dark', 'light']) {
      await page.evaluate(theme => {
        document.documentElement.dataset.theme = theme;
        document.documentElement.classList.remove('light','dark'); document.documentElement.classList.add(theme);
      }, theme);
      const followsTheme = await workspace.evaluate(el => {
        const sample = document.createElement('div'); sample.style.backgroundColor = 'var(--bg-main)'; document.body.append(sample);
        const matches = getComputedStyle(sample).backgroundColor === getComputedStyle(el).backgroundColor; sample.remove(); return matches;
      });
      assert(followsTheme, `${theme} surface differs from app`);
      await page.screenshot({ path: `docs/help/audit/hmi-runtime-${theme}.png` });
    }
    await page.setViewportSize({ width: 390, height: 844 });
    await workspace.getByRole('button', { name: 'Edit layout', exact: true }).click();
    assert(await workspace.evaluate(el => el.getBoundingClientRect().width <= innerWidth), 'Mobile window exceeds viewport');
    await page.screenshot({ path: 'docs/help/audit/hmi-mobile.png' });
    checks.push('App light/dark colors and mobile geometry');
    await page.setViewportSize({ width: 1440, height: 1000 });
    await header.getByRole('button', { name: 'Close', exact: true }).click();
    await page.getByTitle('Generate Engineering Report').click();
    await page.getByRole('button', { name: 'Generate Report', exact: true }).click();
    await page.locator('iframe[title="Report Preview"]').waitFor();
    const preview = page.frameLocator('iframe[title="Report Preview"]');
    await preview.locator('#portable-hmi-canvas').waitFor();
    await preview.locator('#sim-btn-reset').click();
    await preview.locator('[data-hmi-id="h0"] button').press('Enter');
    const step = preview.getByRole('button', { name: 'Step command', exact: true });
    assert(await step.isEnabled(), 'Catalog simulation command disabled');
    await step.click();
    assert((await preview.locator('[data-hmi-id="h2"] svg').textContent()).includes('ACTIVE'), 'Portable chart did not consume staged press');
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: 'HTML', exact: true }).click();
    const output = 'docs/help/audit/hmi-portable-report.html'; await (await download).saveAs(output);
    const portable = await browser.newPage(); portable.on('pageerror', e => errors.push(e.message));
    await portable.goto(pathToFileURL(require('node:path').resolve(output)).href);
    await portable.locator('#portable-hmi-canvas').waitFor();
    await portable.locator('#sim-btn-reset').click();
    await portable.locator('[data-hmi-id="h0"] button').press('Enter');
    await portable.getByRole('button', { name: 'Step command', exact: true }).click();
    assert((await portable.locator('[data-hmi-id="h2"] svg').textContent()).includes('ACTIVE'), 'Downloaded report lost shared runtime interaction');
    await portable.screenshot({ path: 'docs/help/audit/hmi-portable-report.png', fullPage: true });
    await portable.close();
    checks.push('Actual report preview and downloaded HTML consume queued keyboard input through semantic runtime');
    assert(errors.length === 0, errors.join('\n'));
    fs.writeFileSync('docs/help/audit/hmi-browser-verification.json', JSON.stringify({ checks, errors }, null, 2));
    console.log(JSON.stringify({ checks, errors }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
